package com.google.googlejavaformat;

import com.google.common.base.MoreObjects;

/// A `CloseOp` closes a level. It is an [Op] in the sequence of [Op]s generated by [OpsBuilder].
/// When the sequence is turned into a [Doc] by [DocBuilder], ranges delimited by [OpenOp]-`CloseOp`
/// pairs turn into nested [Doc.Level]s.
public enum CloseOp implements Op {
  CLOSE;

  /// Make a `CloseOp`, returning a singleton since they are all the same.
  ///
  /// @return the singleton `CloseOp`
  public static Op make() {
    return CLOSE;
  }

  @Override
  public void add(DocBuilder builder) {
    builder.close();
  }

  @Override
  public String toString() {
    return MoreObjects.toStringHelper(this).toString();
  }
}
